#!/usr/bin/env node
// cms-scaffold.mjs — turns CONTENT.md into the files a site needs to hand its
// owner the keys, and refuses to overwrite anything it did not just write.
//
// CONTENT.md IS THE SOURCE
// ------------------------
// One file is written by hand, by the agency. Everything else is compiled from
// it: the editor's config.yml, the bridge's allow-list, the admin page. Two
// declarations of the same fact drift; one declaration and a generator do not.
// `cms-lint.mjs` then checks the compiled files against that source, which is
// what makes a hand edit visible instead of silent.
//
// It never rewrites an artefact that is already there. A file that exists and
// differs is reported as drift and the run fails, the way build-dist.mjs --check
// does, because a generator that overwrites is a generator that eats the fix
// somebody made at two in the morning.
//
// Usage:
//   node cms-scaffold.mjs init  [root]     write CONTENT.md from what the site already has
//   node cms-scaffold.mjs       [root]     compile CONTENT.md into the artefacts
//   node cms-scaffold.mjs --check [root]   compare only, write nothing
//   node cms-scaffold.mjs --force [root]   rewrite what has drifted

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, dirname, resolve, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parse, stringify } from "./yaml-lite.mjs";
import { contentMap } from "../content-map.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const BUNDLE_VERSION = "3.15.1";
const THEME_SCRIPT = join(HERE, "../../design-system/scripts/theme_css.py");

const DEFAULT_THEME = {
  paper: "#FBFAF7", ink: "#1B1B1B", accent: "#0F6E4F", accent_ink: "#FFFFFF",
  font: "system-ui, sans-serif", radius: 10,
};

// The admin sheet is generated by the design system, not written here, so a
// client's editor carries the same palette as their site rather than a second
// one that drifts. python3 is already what runs the design system's own tests.
export function themeCss(theme) {
  const t = { ...DEFAULT_THEME, ...(theme || {}) };
  return execFileSync("python3", [THEME_SCRIPT, "--format", "decap",
    "--bg", t.paper, "--ink", t.ink, "--accent", t.accent, "--accent-ink", t.accent_ink,
    "--font", t.font, "--radius", String(t.radius)], { encoding: "utf8" });
}

/* ── CONTENT.md ───────────────────────────────────────────────────────────── */

// The prose is for the agency and the client; the fenced block is what compiles.
// Keeping both in one file means the explanation cannot drift from the rule,
// because they are read at the same moment by the same person.
export function readContent(markdown) {
  const fence = /```ya?ml\n([\s\S]*?)\n```/.exec(String(markdown));
  if (!fence) throw new Error("CONTENT.md has no ```yaml block; nothing to compile");
  const declared = parse(fence[1]);
  for (const key of ["branch", "collections", "media"]) {
    if (declared[key] === undefined) throw new Error(`CONTENT.md declares no ${key}`);
  }
  return declared;
}

export function contentTemplate(map, options = {}) {
  const media = map.media.folder
    ? { folder: map.media.folder, public: map.media.publicFolder, max_width: 2000, quality: 0.82 }
    : { folder: "static/uploads", public: "/uploads", max_width: 2000, quality: 0.82 };

  const collections = [...map.collections, ...map.singles].map(entry => ({
    name: entry.name,
    label: entry.name.charAt(0).toUpperCase() + entry.name.slice(1),
    ...(map.singles.includes(entry)
      ? { file: entry.sample }
      : { folder: entry.folder, extension: entry.extension.replace(/^\./, ""), create: true }),
    fields: entry.fields.map(f => ({ name: f.name, label: f.name, widget: f.widget, required: f.required })),
  }));

  const declared = {
    branch: options.branch || "content",
    production_branch: options.productionBranch || "main",
    site: options.site || "",
    roles: ["editor", "manager"],
    theme: { ...DEFAULT_THEME },
    media,
    quota: [{ hours: 1, max: 10 }, { hours: 720, max: 100 }],
    collections,
  };

  const zones = map.hardcoded.length
    ? ["", "## Ce qui n'est pas encore modifiable", "",
       "Ces passages vivent dans un gabarit, donc aucune collection ne les atteint.",
       "Les sortir dans un fichier de contenu est la condition pour les confier.", ""]
      .concat(map.hardcoded.slice(0, 40).map(h => `- \`${h.file}:${h.line}\` ${h.text}`))
    : [];

  return [
    "# Ce que le propriétaire du site peut modifier",
    "",
    "Ce fichier est écrit à la main. Tout le reste en est compilé par",
    "`cms-scaffold.mjs` : la configuration de l'éditeur, la liste blanche du pont,",
    "la page d'administration. Modifier un fichier compilé plutôt que celui-ci fait",
    "échouer `cms-lint.mjs`.",
    "",
    "Les chemins déclarés ici sont les seuls que le pont acceptera d'écrire. Tout ce",
    "qui n'y figure pas est refusé côté serveur, quoi qu'en dise l'interface.",
    "",
    "```yaml",
    stringify(declared),
    "```",
    ...zones,
    "",
  ].join("\n");
}

/* ── what CONTENT.md compiles into ────────────────────────────────────────── */

// A file collection may hold one entry (`file:`) or several (`files:`). The one
// entry form stays because most sites have exactly one, and writing a list of
// one is noise; the list form is what lets a site put every page under a single
// heading instead of one heading per page.
export const filesOf = c => (Array.isArray(c.files) && c.files.length
  ? c.files
  : c.file ? [{ name: c.name, label: c.label, file: c.file, fields: c.fields, roles: c.roles }] : []);

const singlesOf = collections => collections.filter(c => !c.folder).flatMap(filesOf);

const IMAGE_EXTENSIONS = [".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"];
const TEXT_EXTENSIONS = [".md", ".markdown", ".json", ".yml", ".yaml"];

export function policyFrom(declared) {
  const folders = declared.collections.filter(c => c.folder).map(c => c.folder.replace(/\/+$/, ""));
  const roots = folders.filter(f => !folders.some(other => other !== f && f.startsWith(`${other}/`)));
  const rules = [...new Set(roots)].sort().map(prefix => ({
    prefix: `${prefix}/`, extensions: TEXT_EXTENSIONS, roles: [],
  }));
  // A file collection declares one `file:` or a `files:` list; both name exact
  // paths, and an exact path is the tightest rule the bridge can be given.
  for (const single of singlesOf(declared.collections)) {
    if (rules.some(r => single.file.startsWith(r.prefix))) continue;
    if (rules.some(r => r.prefix === single.file)) continue;
    rules.push({ prefix: single.file, extensions: [], roles: single.roles || [] });
  }
  rules.push({ prefix: `${declared.media.folder.replace(/\/+$/, "")}/`, extensions: IMAGE_EXTENSIONS, roles: [] });
  return {
    branch: declared.branch,
    locale: declared.locale || "en",
    // "on_save" : chaque enregistrement met en ligne, c'est le comportement
    // d'origine. "manual" : l'enregistrement reste un brouillon sur la branche
    // de contenu et la mise en ligne se demande depuis l'éditeur.
    publish: declared.publish === "manual" ? "manual" : "on_save",
    publishWorkflow: "publish-content.yml",
    productionBranch: declared.production_branch || "main",
    requiredRoles: declared.roles,
    sessionHours: 8,
    maxSessionHours: 24,
    writeQuota: declared.quota,
    maxFileBytes: 3145728,
    maxRequestBytes: 5242880,
    rules,
  };
}

export function configFrom(declared) {
  return {
    backend: {
      name: "nth",
      proxy_url: "/api/cms",
      branch: declared.branch,
      image_convert: "webp",
      image_max_width: declared.media.max_width,
      image_quality: declared.media.quality,
    },
    ...(declared.site ? { site_url: declared.site } : {}),
    // Les traductions de Decap sont dans le paquet principal, pas dans un
    // morceau chargé à part : déclarer la langue suffit, rien de plus à
    // vendoriser et le compte de morceaux de CMS-25 ne bouge pas.
    ...(declared.locale && declared.locale !== "en" ? { locale: declared.locale } : {}),
    media_folder: declared.media.folder,
    public_folder: declared.media.public,
    publish_mode: "simple",
    collections: declared.collections.map(c => (c.folder ? {
      name: c.name, label: c.label, folder: c.folder,
      extension: c.extension || "md", create: c.create !== false,
      fields: c.fields,
    } : {
      name: c.name, label: c.label,
      files: filesOf(c).map(f => ({ name: f.name, label: f.label, file: f.file, fields: f.fields })),
    })),
  };
}

const HEADERS_BLOCK = [
  "# Decap compiles its config with AJV and renders with Emotion, so the admin",
  "# page needs two exceptions the rest of the site must not have.",
  "/admin/*",
  "  Content-Security-Policy: default-src 'self'; script-src 'self' 'unsafe-eval'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self'",
  "  X-Robots-Tag: noindex",
].join("\n");

// The branch names are the one thing the workflow cannot carry as a constant,
// because they are this site's, and the copier inside it must stay byte for byte
// what the plugin reviewed.
export function workflowFor(declared) {
  const production = declared.production_branch || "main";
  const content = declared.branch;
  for (const name of [production, content]) {
    if (!/^[A-Za-z0-9._\/-]+$/.test(name)) throw new Error(`CONTENT.md: ${name} is not a branch name`);
  }
  if (production === content) throw new Error("CONTENT.md: the content branch and the production branch are the same");
  const yaml = readFileSync(join(HERE, "publish-content.yml"), "utf8")
    .split("NTH_PRODUCTION_BRANCH").join(production)
    .split("NTH_CONTENT_BRANCH").join(content);
  if (declared.publish !== "manual") return yaml;
  // En publication manuelle, enregistrer ne met pas en ligne : le déclencheur
  // sur poussée disparaît et il ne reste que la mise en ligne demandée depuis
  // l'éditeur. Laisser les deux ferait mentir le bouton.
  return yaml.replace(/^on:\n(?:  push:\n    branches: \[[^\]]*\]\n)?  workflow_dispatch:\n/m,
    "on:\n  workflow_dispatch:\n");
}

// La fiche de mise en service. Tout ce qui suit est hors de portée d'un
// générateur : un jeton se crée dans une console GitHub, une variable se pose
// chez l'hébergeur, une branche se pousse. Ce que le plugin peut faire, c'est
// écrire la consigne exacte avec les vrais noms de ce site plutôt qu'un modèle
// à trous, et dire à la fin ce qu'aucun contrôle ne pourra constater.
export function handoverFor(declared) {
  const repo = declared.repo || "<propriétaire/dépôt>";
  const site = declared.site || "<le site chez l'hébergeur>";
  const branch = declared.branch;
  const production = declared.production_branch || "main";
  const roles = (declared.roles || ["editor"]).join(", ");
  return (declared.locale === "fr" ? handoverFr : handoverEn)({ repo, site, branch, production, roles });
}

