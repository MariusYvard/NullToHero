// L'éditeur d'un site se reconnaît à l'icône de ce site, dans l'onglet du
// navigateur comme en haut à droite de la page. Sans icône déclarée, Decap garde
// sa silhouette générique : mieux vaut ne rien changer que peindre un carré vide.
export function faviconBlock(url) {
  if (!url) return "";
  const href = String(url).replace(/["<>]/g, "");
  return [
    `<link rel="icon" href="${href}" />`,
    "<style>",
    '  [class*="AvatarPlaceholderIcon"] > svg { display: none; }',
    `  [class*="AvatarPlaceholderIcon"] { background: url("${href}") center/contain no-repeat; }`,
    "</style>",
  ].join("\n    ");
}

export function artefacts(declared) {
  const admin = readFileSync(join(HERE, "admin-index.html"), "utf8")
    .replace(/decap-cms-VERSION/g, `decap-cms-${BUNDLE_VERSION}`)
    .replace(/ *NTH_FAVICON\n/, faviconBlock(declared.favicon)
      ? `    ${faviconBlock(declared.favicon)}\n` : "");
  return [
    { path: "netlify/functions/cms.mjs", body: readFileSync(join(HERE, "bridge.mjs"), "utf8") },
    { path: "netlify/functions/cms-policy.json", body: `${JSON.stringify(policyFrom(declared), null, 2)}\n` },
    { path: ".github/workflows/publish-content.yml", body: workflowFor(declared) },
    { path: "admin/index.html", body: admin },
    { path: "admin/nth-backend.js", body: readFileSync(join(HERE, "nth-backend.js"), "utf8") },
    // The site's own build calls this once its pages are otherwise final: it
    // resolves the content tokens and writes the copies the editor previews.
    { path: "nth-content.mjs", body: readFileSync(join(HERE, "content-fill.mjs"), "utf8") },
    { path: "admin/config.yml", body: `${configHeader()}${stringify(configFrom(declared))}\n` },
    { path: "admin/theme.css", body: themeCss(declared.theme) },
    { path: "ATTRIBUTION.md", body: attribution() },
    { path: "CMS.md", body: handoverFor(declared) },
    { path: "_headers", body: `${HEADERS_BLOCK}\n`, appendOnly: true },
  ];
}

