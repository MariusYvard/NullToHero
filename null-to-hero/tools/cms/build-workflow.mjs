#!/usr/bin/env node
// build-workflow.mjs — writes publish-content.yml with publish.mjs inlined.
//
//   node build-workflow.mjs [--check]
//
// The copier has to live inside `.github/workflows/`, because that is the one
// path a fine-grained token without the `Workflows` permission cannot write, and
// that guarantee comes from GitHub rather than from our own code being right.
// GitHub's own documentation does not say whether the permission covers every
// file in that directory or only the workflow YAML, so the copier goes inside the
// YAML, where the answer is not in doubt.
//
// That leaves two copies of the same source, which is why this script exists and
// why `--check` runs in CI.

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const MARK = "NTH_PUBLISH_EOF";
const INDENT = " ".repeat(10);

const head = `name: publish-content

# Moves the allow-listed paths from the content branch onto the production
# branch. It does not merge: a merge would carry whatever else the content
# branch holds, and a rewritten package.json runs as a build script.
#
# Generated by null-to-hero/tools/cms/build-workflow.mjs from
# publish.mjs, then written by cms-scaffold.mjs with this site's branch names
# substituted. Edit CONTENT.md, not this file.

on:
  push:
    branches: [NTH_CONTENT_BRANCH]
  workflow_dispatch:

permissions:
  contents: write

concurrency:
  group: publish-content
  cancel-in-progress: false

jobs:
  publish:
    runs-on: ubuntu-latest
    steps:
      - name: Check out the production branch
        uses: actions/checkout@v4
        with:
          ref: NTH_PRODUCTION_BRANCH
          path: prod
          fetch-depth: 0

      # The content branch is the one a client can move, so the write token is
      # not left in its checkout. Nothing runs from that directory today; this
      # keeps that true if a step is ever added.
      - name: Check out the content branch
        uses: actions/checkout@v4
        with:
          ref: NTH_CONTENT_BRANCH
          path: incoming
          persist-credentials: false

      # What the content branch changed is measured against its fork point, not
      # against production. Otherwise every file the agency touches on production
      # reads as a difference, and a file the agency adds to production reads as
      # something the client deleted.
      #
      # Every network call runs from the production checkout, the one that still
      # holds a token, so the credential-free checkout stays credential-free.
      - name: Find the fork point
        working-directory: prod
        run: |
          git fetch --no-tags origin NTH_CONTENT_BRANCH:refs/nth/content
          BASE="$(git merge-base HEAD refs/nth/content)"
          echo "fork point $(git rev-parse --short "$BASE")"
          git ls-tree -r -z "$BASE" > /tmp/nth-base.txt

      # The allow-list is read from the production branch, never from the branch
      # being published, so a compromised bridge cannot widen the list it is
      # about to be measured against.
      - name: Copy only the allow-listed paths
        run: |
          cat > /tmp/publish.mjs <<'${MARK}'
`;

const tail = `          ${MARK}
          node /tmp/publish.mjs \\
            --policy prod/netlify/functions/cms-policy.json \\
            --from incoming --to prod \\
            --base /tmp/nth-base.txt \\
            --changed /tmp/nth-changed.txt

      # Staging exactly what was copied, forced, so a path production happens to
      # ignore cannot produce a green run that published nothing.
      - name: Commit the result
        working-directory: prod
        run: |
          if [ ! -s /tmp/nth-changed.txt ]; then
            echo "nothing to publish"
            exit 0
          fi
          git config user.name "nth-content-bot"
          git config user.email "nth-content-bot@users.noreply.github.com"
          git add --all --force --pathspec-from-file=/tmp/nth-changed.txt --pathspec-file-nul
          if git diff --cached --quiet; then
            echo "::error::the copier touched files but git staged nothing"
            exit 1
          fi
          git commit -m "content: publish the allow-listed paths"
          git push origin HEAD:NTH_PRODUCTION_BRANCH
`;

const source = readFileSync(join(HERE, "publish.mjs"), "utf8");
if (source.includes(MARK)) {
  console.error(`publish.mjs contains ${MARK}, which would close the heredoc early`);
  process.exit(1);
}
const body = source.replace(/\r\n/g, "\n").split("\n")
  .map(line => (line ? INDENT + line : line)).join("\n");
const out = head + body + tail;

const target = join(HERE, "publish-content.yml");
if (process.argv.includes("--check")) {
  const have = readFileSync(target, "utf8");
  if (have !== out) {
    console.error("publish-content.yml is out of date. Run: node build-workflow.mjs");
    process.exit(1);
  }
  console.log("publish-content.yml matches publish.mjs");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
