const GATE = resolve("tools/audit/gate.mjs");
const gate = (args) => {
  try { execFileSync("node", [GATE, ...args], { stdio: ["ignore", "pipe", "pipe"] }); return 0; }
  catch (e) { return e.status ?? -1; }
};
const gtmp = mkdtempSync(join(tmpdir(), "nth-gate-"));
